    root = Path(__file__).absolute().parent
    if (not output.is_absolute() or output != root / 'observations'
            or not re.fullmatch(r'AttuneT2Proof-[0-9a-f]{32}', root.name)
            or output.exists()):
        raise ValueError('Require the unchanged fixture new observations leaf')
    artifacts = root / 'artifacts'
    if not artifacts.is_dir():
        raise ValueError('The unchanged fixture artifacts directory is absent')
    receipt_path = artifacts / 'combined-driver.json'
    if receipt_path.exists():
        raise ValueError('Refuse retained driver evidence')
    report = {'experiment': 'combined_saved_store_observations_v3',
              'status': 'started', 'aggregate_seconds': AGGREGATE_SECONDS,
              'original_sha256': ORIGINAL_SHA, 'namespace_sha256': NAMESPACE_SHA,
              'expected_native_sha256': NATIVE_SHA, 'phases': [],
              't2_d3_gate': 'unpassed', 'production_port_allowed': False,
              'power_loss_tested': False, 'provider_calls': 0,
              'anchor_precondition': 'existing fixture root; its publication not qualified'}

    def checkpoint():
        receipt_path.write_text(json.dumps(report, ensure_ascii=True, allow_nan=False,
                                           sort_keys=True, indent=2) + '\n', encoding='ascii')
        emit({'event': 'combined_driver', **report})

    started = time.monotonic()
    try:
        checkpoint()
        # Import only in the future authorized process, never in pure tests.
        from attune_harness import windows_effects
        native_path = Path(windows_effects.__file__).resolve()
        if ('site-packages' not in native_path.parts or
                hashlib.sha256(native_path.read_bytes()).hexdigest() != NATIVE_SHA):
            raise ValueError('Require the exact installed native source')
        source_dir = root / 'combined-witness-sources'
        source_dir.mkdir()
        for name, data in [('original.py', payload_bytes(ORIGINAL_PAYLOAD, ORIGINAL_SHA)),
                           ('namespace_v4.py', payload_bytes(NAMESPACE_PAYLOAD, NAMESPACE_SHA))]:
            with (source_dir / name).open('xb') as stream:
                stream.write(data)
        for phase, command in command_plan(sys.executable, source_dir, output):
            entry = {'phase': phase, 'status': 'dispatching'}
            report['phases'].append(entry)
            checkpoint()
            # Keep descendants inside the already-owned outer fixture Job.
            # Timeout alone does not establish the complete process tree empty.
            result = subprocess.run(command, stdin=subprocess.DEVNULL,
                                    timeout=remaining_budget(started, time.monotonic()), check=False)
            entry.update(status='returned', exit_code=result.returncode)
            checkpoint()
            if result.returncode != 0:
                raise RuntimeError('A pinned observation process failed: ' + phase)
        report['status'] = 'observation_processes_returned_zero'
        checkpoint()
        return 0
    except BaseException as exc:
        report.update(status='failed', failure_type=type(exc).__name__)
        checkpoint()
        raise


