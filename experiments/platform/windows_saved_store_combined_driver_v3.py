def payload_bytes(encoded, expected):
    raw = base64.b64decode(encoded, validate=True)
    if len(raw) > 1024 * 1024 or hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError('Embedded proof bytes differ from the reviewed source')
    return raw


